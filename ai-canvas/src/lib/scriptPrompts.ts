/** 用户输入区：把 config + 素材清单填入【用户输入】，喂给模型。 */
export function buildSeedanceUserPrompt(config: ScriptConfig, manifest: MaterialManifestItem[]): string {
  const imgLines = manifest.length
    ? manifest.map((m) => `- @${m.mention}（${typeLabel(m.type)}）`).join("\n")
    : "（已在随附图片中按【图N】标注，请逐张分析）";
  const notes = config.notes?.trim() || "（无）";
  return `【用户输入】

产品图片：
${imgLines}

业务场景：
${businessLabel(config.business)}

语言：
${languageLabel(config.language)}

内容类型：
${contentTypeLabel(config.contentType)}

视频时长：
${config.durationSeconds || 30}秒

补充说明：
${notes}

请严格按系统指令的【输出格式】完整输出八个部分（产品分析结果 → 脚本方向 →（剧情演绎时）小反转设计 → 分镜脚本表 → 逐镜 Seedance 2.0 提示词 → 总提示词 → 声音文案 → 风险检查）。引用产品图只用上面列出的「图N」标签，画面中严禁出现任何文字。`;
}
